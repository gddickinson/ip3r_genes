"""S6 — renders `results/msa_v2/report.md` purely from the committed tables.

D13: nothing in that report is hand-written. Scope and instrument live here,
results in `s6_report_results.py` (the `s3_report.py` / `s3_report_d10.py`
split, so both halves stay under 500 lines and cannot read the tables
differently — the results half takes this module's loader and formatter).

Run:  /opt/anaconda3/envs/piezo1/bin/python scripts/s6_report.py
"""

